"""Spotify auth, Liked Songs pagination, and playlist sync.

Playlist calls go through spotipy's low-level helpers on purpose: Spotify's February 2026
changes renamed ``/playlists/{id}/tracks`` -> ``/items`` and replaced
``POST /users/{id}/playlists`` with ``POST /me/playlists``, and spotipy's convenience
wrappers may still target the old paths.
"""
from __future__ import annotations

import logging
from collections.abc import Iterator
from typing import Any

import spotipy
from spotipy.exceptions import SpotifyException
from spotipy.oauth2 import SpotifyOAuth

from config import Settings
from db import chunked
from models import Track

log = logging.getLogger(__name__)

SCOPES = "user-library-read playlist-modify-public playlist-modify-private"
PAGE_SIZE = 50  # hard maximum for /me/tracks
PLAYLIST_BATCH = 100  # hard maximum URIs per write call


def _normalise_isrc(raw: str | None) -> str | None:
    if not raw:
        return None
    isrc = raw.replace("-", "").strip().upper()
    return isrc or None


def item_to_track(item: dict[str, Any]) -> Track | None:
    """Convert one saved-track item; None for local files / removed / non-track entries."""
    track = item.get("track")
    if not track or track.get("is_local") or not track.get("id"):
        return None
    if track.get("type", "track") != "track":
        return None
    artists = [a.get("name", "") for a in track.get("artists", []) if a.get("name")]
    return Track(
        spotify_id=track["id"],
        name=track.get("name", ""),
        primary_artist=artists[0] if artists else "",
        artists=", ".join(artists) or "Unknown artist",
        album=(track.get("album") or {}).get("name"),
        duration_ms=track.get("duration_ms"),
        isrc=_normalise_isrc((track.get("external_ids") or {}).get("isrc")),
        added_at=item.get("added_at"),
    )


class SpotifyClient:
    def __init__(self, settings: Settings) -> None:
        auth = SpotifyOAuth(
            client_id=settings.spotify_client_id,
            client_secret=settings.spotify_client_secret,
            redirect_uri=settings.spotify_redirect_uri,
            scope=SCOPES,
            cache_path=str(settings.token_cache_path),
            open_browser=True,
        )
        # spotipy honours Retry-After on 429 via urllib3 retries.
        self.sp = spotipy.Spotify(
            auth_manager=auth, requests_timeout=settings.http_timeout,
            retries=5, status_retries=5, backoff_factor=0.5,
        )

    # ---- Liked Songs -----------------------------------------------------------
    def liked_total(self) -> int:
        return int(self.sp.current_user_saved_tracks(limit=1)["total"])

    def iter_liked_tracks(self, known_ids: set[str] | None = None) -> Iterator[Track]:
        """Yield every liked track, newest first.

        Follows the API's own ``next`` URL (50 items/page) instead of computing offsets,
        so the walk stays correct even if the library changes mid-scan. With ``known_ids``
        it stops after the first page consisting entirely of already-known tracks - since
        the list is newest-first, nothing older can be new.
        """
        page: dict[str, Any] | None = self.sp.current_user_saved_tracks(limit=PAGE_SIZE, offset=0)
        while page:
            page_tracks = [t for t in map(item_to_track, page.get("items", [])) if t]
            yield from page_tracks
            if known_ids is not None and page.get("items") and all(
                t.spotify_id in known_ids for t in page_tracks
            ):
                return
            page = self.sp.next(page) if page.get("next") else None

    # ---- Playlists --------------------------------------------------------------
    def create_playlist(self, name: str, description: str, public: bool) -> str:
        data = self.sp._post(
            "me/playlists",
            payload={"name": name, "description": description, "public": public},
        )
        return str(data["id"])

    def replace_playlist_items(self, playlist_id: str, track_ids: list[str]) -> None:
        uris = [f"spotify:track:{tid}" for tid in track_ids]
        first, rest = uris[:PLAYLIST_BATCH], uris[PLAYLIST_BATCH:]
        # PUT replaces the whole playlist (an empty list clears it); POST appends.
        self.sp._put(f"playlists/{playlist_id}/items", payload={"uris": first})
        for chunk in chunked(rest, PLAYLIST_BATCH):
            self.sp._post(f"playlists/{playlist_id}/items", payload={"uris": chunk})

    def sync_playlist(
        self, name: str, track_ids: list[str], existing_id: str | None, public: bool
    ) -> str:
        """Make the playlist contain exactly ``track_ids``; create it if needed/deleted."""
        description = "Generated by Spotify Language Sorter"
        if existing_id:
            try:
                self.replace_playlist_items(existing_id, track_ids)
                return existing_id
            except SpotifyException as exc:
                if exc.http_status != 404:
                    raise
                log.warning("playlist %s no longer exists, recreating", name)
        playlist_id = self.create_playlist(name, description, public)
        self.replace_playlist_items(playlist_id, track_ids)
        return playlist_id
